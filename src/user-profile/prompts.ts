export function withUserProfileOutputLanguage(
  systemPrompt: string,
  language: ProjectWikiPromptLanguage,
): string {
  return [
    systemPrompt,
    "",
    "UserProfile output language:",
    `- Write generated user profile content in ${projectWikiLanguageName(language)}.`,
    "- Preserve code identifiers, file paths, product names, and exact quoted source text in their original language.",
    `- If evidence is in another language, summarize durable facts in ${projectWikiLanguageName(language)}.`,
  ].join("\n");
}
